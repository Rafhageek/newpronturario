export interface Cid10Chapter {
  /** Número do capítulo (1 a 22), como no DATASUS. */
  number: number;
  /** Algarismo romano usado nas publicações ("I", "II"…). */
  roman: string;
  /** Primeira categoria do capítulo (ex.: "A00"). */
  start: string;
  /** Última categoria do capítulo (ex.: "B99"). */
  end: string;
  /** Título oficial do capítulo, sem o prefixo "Capítulo N - ". */
  title_pt: string;
}

export interface Cid10Category {
  /** Categoria de 3 dígitos (ex.: "I10"). Sempre maiúscula. */
  code: string;
  /** Descrição oficial do DATASUS, sem alteração. */
  description_pt: string;
  /** Número do capítulo a que a categoria pertence. */
  chapter: number;
}

